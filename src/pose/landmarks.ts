export type Point = {
  x: number
  y: number
  visibility?: number
}

export function midpoint(a: Point, b: Point): Point {
  return { x: (a.x + b.x) / 2, y: (a.y + b.y) / 2 }
}

export function visibleEnough(p: Point, min = 0.45): boolean {
  return (p.visibility ?? 1) >= min
}
